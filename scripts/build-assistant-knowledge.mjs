import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import yaml from 'js-yaml';

const root = fileURLToPath(new URL('../', import.meta.url));
export const MAX_SOURCE_BYTES = 24000;

// This is a deliberate allowlist. No Markdown, PDF, private files, case-study
// prose, or visitor content is ingested. facts.yaml remains the only authority.
export function buildKnowledge(facts, sourceText) {
  const site = facts.meta.site_url;
  if (site !== 'https://sarthak0501.github.io') throw new Error('Unexpected canonical site');
  const sources = [];
  const add = (id, title, relative, text) => {
    if (!/^[a-z][a-z0-9-]{0,63}$/.test(id) || sources.some(s => s.id === id)) throw new Error('Invalid source ID');
    const url = new URL(relative, `${site}/`);
    if (url.origin !== site || !relative.startsWith('/')) throw new Error('Invalid canonical source URL');
    if (typeof text !== 'string' || !text.trim()) throw new Error('Empty source');
    sources.push({ id, title, url: url.href, text: text.trim() });
  };
  const i = facts.identity;
  add('profile', 'Profile and contact', '/resume/', [
    `Name: ${i.name}. Role: ${i.title}, ${i.org}, ${i.team}.`,
    `Location: ${i.location}. Current tenure began: ${i.tenure_start}. Experience: ${i.years} years.`,
    `Scope: ${i.scope}. Status: ${i.status}. Interested roles: ${i.open_to.join('; ')}.`,
    `Public contact: ${i.email}. LinkedIn: ${i.linkedin}. GitHub: ${i.github}.`
  ].join('\n'));
  for (const record of facts.record) {
    const lines = [`${record.role}, ${record.company}, ${record.location}; ${record.dates}.`];
    if (record.scope) lines.push(record.scope);
    if (record.leadership_band) lines.push('Leadership: ' + record.leadership_band.join('; '));
    for (const stream of record.workstreams || []) lines.push(`${stream.name}:\n${stream.bullets.join('\n')}`);
    if (record.bullets) lines.push(...record.bullets);
    add(record.id, `${record.company} experience`, `/resume/#${record.id}`, lines.join('\n'));
  }
  for (const [id, text] of Object.entries(facts.skills)) {
    add(`skills-${id.replaceAll('_', '-')}`, `Skills — ${id === 'ai_ml' ? 'AI / ML' : id}`, '/resume/', text);
  }
  add('education', 'Education', '/resume/', facts.education.map(e => `${e.degree}, ${e.school}, ${e.dates}.`).join('\n'));
  for (const system of facts.systems) {
    add(system.id.toLowerCase(), system.name, system.link,
      `${system.what}\nEvidence: ${system.proof}. Status: ${system.status}.`);
  }
  for (const receipt of facts.receipts) {
    add(`receipt-${receipt.id}`, receipt.label, receipt.anchor,
      `${receipt.value} — ${receipt.label}. ${receipt.sub}.`);
  }
  if (new TextEncoder().encode(JSON.stringify(sources)).length > MAX_SOURCE_BYTES) throw new Error('Approved corpus exceeds source byte budget');
  return {
    version: 1,
    revision: facts.meta.resume_rev,
    factsSha256: createHash('sha256').update(sourceText).digest('hex'),
    sources
  };
}

export async function generateKnowledge() {
  const sourceText = await readFile(path.join(root, 'src/_data/facts.yaml'), 'utf8');
  const knowledge = buildKnowledge(yaml.load(sourceText), sourceText);
  const rendered = `// Generated by scripts/build-assistant-knowledge.mjs from public facts.yaml only.\n// Do not edit by hand.\nexport default ${JSON.stringify(knowledge, null, 2)};\n`;
  await mkdir(path.join(root, 'assistant'), { recursive: true });
  await writeFile(path.join(root, 'assistant/knowledge.generated.mjs'), rendered);
  return knowledge;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const knowledge = await generateKnowledge();
  console.log(`Assistant knowledge: ${knowledge.sources.length} approved public sources; revision ${knowledge.revision}.`);
}
